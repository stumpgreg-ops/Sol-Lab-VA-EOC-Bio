/* Write js/standards-bio.js from the standards map in js/content.js (HEIST_STANDARDS): node tools/make-standards-bio.js
   The teacher page's standards report (tools/teacher/teacher.js, v5.17) reads window.SolStandards for each standard's
   official text; tools/build-teacher.js inlines the file into teacher/BIO.html. Biology's key ideas (BIO.8.a) are the
   codes a question carries, so each is a "standard" here with the text of its key idea, and the eight standards
   (BIO.1 to BIO.8) are listed too. There is no LOTS/HOTS skill split (SKILL is empty). */
var fs = require("fs"), path = require("path"), vm = require("vm");
var root = path.join(__dirname, "..");
var win = {}; win.window = win;
vm.runInNewContext(fs.readFileSync(path.join(root, "js", "content.js"), "utf8"), Object.assign({ window: win }, win));
var STD = win.HEIST_STANDARDS;
if (!STD) throw new Error("tools/make-standards-bio.js: js/content.js gave no HEIST_STANDARDS");
var out = {};
Object.keys(STD).forEach(function (code) {
  out[code] = { text: "Standard " + code + ": " + STD[code].name + ".", skills: [] };
  Object.keys(STD[code].keys).forEach(function (k) {
    var t = STD[code].keys[k];
    out[code + "." + k] = { text: STD[code].name + ": " + t.charAt(0).toUpperCase() + t.slice(1) + ".", skills: [] };
  });
});
var js = "/* SOL Lab Biology: the 2018 Virginia Biology Standards of Learning (BIO.1 to BIO.8) and their key ideas (BIO.8.a), with\n" +
  "   the text the teacher page's standards report shows for each (tools/teacher/teacher.js reads window.SolStandards).\n" +
  "   GENERATED by node tools/make-standards-bio.js from the standards map in js/content.js: edit that map and rebuild. */\n" +
  "(function (root) {\n  \"use strict\";\n  var STANDARDS = " + JSON.stringify(out, null, 1) + ";\n" +
  "  var SKILL = {};\n  Object.keys(STANDARDS).forEach(function (code) { STANDARDS[code].skills.forEach(function (s) { SKILL[s.id] = { code: code, text: s.text, level: s.level }; }); });\n" +
  "  var api = { STANDARDS: STANDARDS, SKILL: SKILL };\n  if (typeof module !== \"undefined\" && module.exports) module.exports = api;\n  if (root) root.SolStandards = api;\n" +
  "})(typeof window !== \"undefined\" ? window : (typeof globalThis !== \"undefined\" ? globalThis : this));\n";
fs.writeFileSync(path.join(root, "js", "standards-bio.js"), js);
console.log("js/standards-bio.js: " + Object.keys(out).length + " entries (" + Object.keys(STD).length + " standards and their key ideas)");
