/* node tools/build-standards.js : writes js/standards-alg.js from the standards map in js/content.js.
   The SOL Labyrinth backbone (v5.17) gives each game a standards file (js/standards-va.js for Reading) that the
   teacher screen's standards report reads: for each standard its text and its SKILLS, each LOTS (lower-order:
   remember / understand / apply) or HOTS (higher-order: analyze / evaluate). For Algebra I a standard is A.EO.1 …
   A.ST.1 and its skills are the lettered knowledge-and-skills statements (A.EO.1.a …), which is also what each
   question's `sol` code names, so the progress record's per-code results group under their standard without a
   `sub` field. Run it after any change to HEIST_STANDARDS. */
var fs = require("fs"), path = require("path");
var root = path.join(__dirname, "..");
global.window = undefined;
require(path.join(root, "js", "content.js"));
var STD = global.HEIST_STANDARDS;
/* higher-order when the statement asks students to analyze, compare, justify, verify, investigate, connect or conclude */
var HOTS = /analy|compar|justif|verif|investigat|connection|deriv|strengths and weaknesses|evaluate the strength|information revealed|explain the meaning|meaning of|conclusions|reasonableness|whether/i;
var out = {};
Object.keys(STD).forEach(function (code) {
  var d = STD[code];
  out[code] = { text: d.name, skills: Object.keys(d.keys).map(function (L) { return { id: code + "." + L, text: d.keys[L], level: HOTS.test(d.keys[L]) ? "HOTS" : "LOTS" }; }) };
});
var js = "/* SOL Lab Algebra I: the 2023 Virginia Algebra I Standards of Learning the game reviews, for the teacher screen's\n" +
"   standards report (the SOL Labyrinth backbone's js/standards-<game>.js, v5.17). GENERATED by tools/build-standards.js\n" +
"   from HEIST_STANDARDS in js/content.js: edit there and rebuild. A standard's skills are its lettered statements, each\n" +
"   LOTS (lower-order: translate, evaluate, simplify, factor, solve, graph, write) or HOTS (higher-order: analyze,\n" +
"   compare, justify, verify, investigate, interpret in context, draw conclusions). */\n" +
"(function (root) {\n  \"use strict\";\n  var STANDARDS = " + JSON.stringify(out, null, 1) + ";\n" +
"  var SKILL = {};\n  Object.keys(STANDARDS).forEach(function (code) { STANDARDS[code].skills.forEach(function (s) { SKILL[s.id] = { code: code, text: s.text, level: s.level }; }); });\n" +
"  var api = { STANDARDS: STANDARDS, SKILL: SKILL };\n  if (typeof module !== \"undefined\" && module.exports) module.exports = api;\n  if (root) root.SolStandards = api;\n" +
"})(typeof window !== \"undefined\" ? window : (typeof globalThis !== \"undefined\" ? globalThis : this));\n";
fs.writeFileSync(path.join(root, "js", "standards-alg.js"), js);
var n = 0, h = 0; Object.keys(out).forEach(function (k) { out[k].skills.forEach(function (s) { n++; if (s.level === "HOTS") h++; }); });
console.log("js/standards-alg.js: " + Object.keys(out).length + " standards, " + n + " skills (" + h + " HOTS)");
